mirror::FivePoints MainWindow::readFivePoints() const {
    mirror::FivePoints points;
    mirror::Vec3* targets[5] = {&points.p0, &points.pxPlus, &points.pxMinus,
                                &points.pyPlus, &points.pyMinus};
    for (int row = 0; row < 5; ++row) {
        double values[3]{};
        for (int column = 1; column < 4; ++column) {
            const QTableWidgetItem* item = m_pointsTable->item(row, column);
            bool ok = false;
            const double value = item ? item->text().trimmed().toDouble(&ok) : 0.0;
            if (!ok) {
                const QByteArray message =
                    U8("第 %1 行第 %2 列不是有效数字")
                        .arg(row + 1).arg(column + 1).toUtf8();
                throw std::runtime_error(message.constData());
            }
            values[column - 1] = value;
        }
        *targets[row] = {values[0], values[1], values[2]};
    }
    return points;
}

mirror::MirrorParameters MainWindow::readMirrorParameters() const {
    return {m_diameter->value(), m_radius->value(), m_conicK->value()};
}

mirror::TrajectoryOptions MainWindow::readTrajectoryOptions() const {
    mirror::TrajectoryOptions options;
    options.pathType = static_cast<mirror::PathType>(m_pathType->currentData().toInt());
    options.edgeMarginMm = m_edgeMargin->value();
    options.pathPitchMm = m_pathPitch->value();
    options.pointSpacingMm = m_pointSpacing->value();
    options.normalOffsetMm = m_normalOffset->value();
    options.approachClearanceMm = m_clearance->value();
    options.rollOffsetDeg = m_rollOffset->value();
    options.reversePath = m_pathDirection->currentData().toBool();
    options.toolZMode = static_cast<mirror::ToolZMode>(m_toolZMode->currentData().toInt());
    options.orientationReference = static_cast<mirror::OrientationReference>(
        m_orientationReference->currentData().toInt());
    options.maxPoints = static_cast<std::size_t>(m_maxPoints->value());
    return options;
}

mirror::KrlOptions MainWindow::readKrlOptions() const {
    mirror::KrlOptions options;
    options.programName = toUtf8String(m_programName->text().trimmed());
    options.toolIndex = m_toolIndex->value();
    options.baseIndex = m_baseIndex->value();
    options.velocityCp = m_velocity->value();
    options.accelerationCp = m_acceleration->value();
    options.approximationCdisMm = m_cdis->value();
    options.useCdis = m_useCdis->isChecked();
    options.writeBaseDataAtRuntime = m_writeBaseRuntime->isChecked();
    return options;
}

void MainWindow::loadExamplePoints() {
    try {
        const mirror::MirrorParameters mp{};
        const mirror::Mat3 rotation = mirror::kukaABCToMatrix({0.0, -20.8, 0.0});
        const mirror::Vec3 translation{1440.0, -125.0, 520.0};
        const double radius = 250.0;
        const double sag = mirror::asphereSag(mp, radius);
        auto toWorld = [&](const mirror::Vec3& p) { return rotation * p + translation; };
        const mirror::Vec3 values[5] = {
            toWorld({0.0, 0.0, 0.0}),
            toWorld({radius, 0.0, sag}),
            toWorld({-radius, 0.0, sag}),
            toWorld({0.0, radius, sag}),
            toWorld({0.0, -radius, sag})
        };
        for (int row = 0; row < 5; ++row) {
            m_pointsTable->item(row, 1)->setText(f(values[row].x));
            m_pointsTable->item(row, 2)->setText(f(values[row].y));
            m_pointsTable->item(row, 3)->setText(f(values[row].z));
        }
        if (m_pathType) m_pathType->setCurrentIndex(m_pathType->findData(static_cast<int>(mirror::PathType::ConcentricOutsideIn)));
        if (m_edgeMargin) m_edgeMargin->setValue(15.0);
        if (m_pathPitch) m_pathPitch->setValue(30.0);
        if (m_pointSpacing) m_pointSpacing->setValue(12.0);
        if (m_clearance) m_clearance->setValue(30.0);
        if (m_programName) m_programName->setText(U8("CIRCLE_IN"));
        statusBar()->showMessage(U8("已载入完整测试数据：BASE X=1440, Y=-125, Z=520, B=-20.8°，轨迹为同心圆从外向内，所有圆保持同一方向。"), 7000);
    } catch (const std::exception& exception) {
        showError(QString::fromUtf8(exception.what()));
    }
}

void MainWindow::calculateBase() {
    try {
        mirror::Diagnostics diagnostics;
        const mirror::RealBase base = mirror::buildRealBase(readFivePoints(), diagnostics);
        m_lastBase = base;
        m_lastDiagnostics = diagnostics;
        updateBaseDisplays(base, diagnostics);
        statusBar()->showMessage(U8("真实镜面 BASE 计算完成。"), 5000);
    } catch (const std::exception& exception) {
        showError(QString::fromUtf8(exception.what()));
    }
}

void MainWindow::generateProgram() {
    try {
        const mirror::GeneratedOutput output = mirror::generateKrlOutput(
            readFivePoints(), readMirrorParameters(), readTrajectoryOptions(), readKrlOptions());
        m_lastOutput = output;
        m_lastBase = output.base;
        m_lastDiagnostics = output.diagnostics;
        updateBaseDisplays(output.base, output.diagnostics);
        updateOutputDisplays(output);
        statusBar()->showMessage(U8("轨迹与 KRL 程序生成完成。"), 5000);
    } catch (const std::exception& exception) {
        showError(QString::fromUtf8(exception.what()));
    }
}

void MainWindow::updateBaseDisplays(const mirror::RealBase& base,
                                    const mirror::Diagnostics& diagnostics) {
    QString text;
    text += U8("X_M in WORLD = %1\n").arg(vec(base.exW));
    text += U8("Y_M in WORLD = %1\n").arg(vec(base.eyW));
    text += U8("Z_M in WORLD = %1\n\n").arg(vec(base.ezW));
    text += U8("R_WM =\n");
    for (int row = 0; row < 3; ++row) {
        text += U8("[%1, %2, %3]\n")
                    .arg(f(base.R_WM.m[row][0]), f(base.R_WM.m[row][1]), f(base.R_WM.m[row][2]));
    }
    text += U8("\nT_WM = %1\n\n").arg(vec(base.T_WM));
    text += U8("BASE_DATA = %1\n").arg(frameText(base.kukaBase));
    m_baseResult->setPlainText(text);

    QString diag;
    diag += U8("X 对称点半径差：%1 mm\n").arg(f(diagnostics.xPairRadiusMismatch));
    diag += U8("Y 对称点半径差：%1 mm\n").arg(f(diagnostics.yPairRadiusMismatch));
    diag += U8("|X·Y|：%1\n|X·Z|：%2\n|Y·Z|：%3\n")
                .arg(f(diagnostics.exDotEy), f(diagnostics.exDotEz), f(diagnostics.eyDotEz));
    diag += U8("det(R_WM)：%1\n").arg(f(diagnostics.determinantR));
    diag += U8("X 中点横向误差：%1 mm\n").arg(f(diagnostics.xMidCrossTrack));
    diag += U8("Y 中点横向误差：%1 mm\n").arg(f(diagnostics.yMidCrossTrack));
    diag += U8("X 中点矢高：%1 mm\n").arg(f(diagnostics.xMidSag));
    diag += U8("Y 中点矢高：%1 mm\n\n").arg(f(diagnostics.yMidSag));
    diag += U8("建议：对称点半径差和中点横向误差应按实际工艺公差控制；det(R) 应接近 1。\n");
    m_diagnosticsResult->setPlainText(diag);
}

