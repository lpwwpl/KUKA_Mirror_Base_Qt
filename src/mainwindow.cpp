void MainWindow::importPointsCsv() {
    const QString path = QFileDialog::getOpenFileName(
        this, U8("导入五点 CSV"), QString(), U8("CSV 文件 (*.csv *.txt);;所有文件 (*.*)"));
    if (path.isEmpty()) return;

    QFile file(path);
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) {
        showError(file.errorString());
        return;
    }
    QTextStream stream(&file);
    stream.setCodec("UTF-8");
    QMap<QString, int> rowMap{{"P0", 0}, {"PX+", 1}, {"PX-", 2}, {"PY+", 3}, {"PY-", 4}};
    int loaded = 0;
    while (!stream.atEnd()) {
        QString line = stream.readLine().trimmed();
        if (line.isEmpty() || line.startsWith('#')) continue;
        line.replace(';', ',');
        line.replace('\t', ',');
        const QStringList fields = line.split(',', QString::KeepEmptyParts);
        if (fields.size() < 4) continue;
        const QString key = fields[0].trimmed().toUpper();
        if (!rowMap.contains(key)) continue;
        bool okX=false, okY=false, okZ=false;
        const double x = fields[1].trimmed().toDouble(&okX);
        const double y = fields[2].trimmed().toDouble(&okY);
        const double z = fields[3].trimmed().toDouble(&okZ);
        if (!(okX && okY && okZ)) continue;
        const int row = rowMap.value(key);
        m_pointsTable->item(row, 1)->setText(f(x));
        m_pointsTable->item(row, 2)->setText(f(y));
        m_pointsTable->item(row, 3)->setText(f(z));
        ++loaded;
    }
    if (loaded != 5) {
        showError(U8("CSV 未完整读取 5 个点。名称必须为 P0、PX+、PX-、PY+、PY-。"));
        return;
    }
    calculateBase();
}

void MainWindow::exportPointsCsv() {
    try {
        const mirror::FivePoints p = readFivePoints();
        const QString path = QFileDialog::getSaveFileName(
            this, U8("保存五点 CSV"), U8("five_points.csv"), U8("CSV 文件 (*.csv)"));
        if (path.isEmpty()) return;
        QString text = U8("name,x,y,z\n");
        const QStringList names{"P0", "PX+", "PX-", "PY+", "PY-"};
        const mirror::Vec3 values[5]{p.p0, p.pxPlus, p.pxMinus, p.pyPlus, p.pyMinus};
        for (int i = 0; i < 5; ++i) {
            text += U8("%1,%2,%3,%4\n")
                        .arg(names[i], f(values[i].x), f(values[i].y), f(values[i].z));
        }
        QString error;
        if (!writeUtf8File(path, text, error)) showError(error);
    } catch (const std::exception& exception) {
        showError(QString::fromUtf8(exception.what()));
    }
}

void MainWindow::exportGeneratedSrc() {
    if (!m_lastOutput) {
        showError(U8("请先生成轨迹和 KRL 程序。"));
        return;
    }

    const QString program = fromUtf8String(
        mirror::sanitizeKrlIdentifier(readKrlOptions().programName));
    const QString path = QFileDialog::getSaveFileName(
        this,
        U8("保存 KUKA SRC 程序"),
        program + U8(".src"),
        U8("KUKA SRC 程序 (*.src);;所有文件 (*.*)"));
    if (path.isEmpty()) return;

    QString finalPath = path;
    if (!finalPath.endsWith(U8(".src"), Qt::CaseInsensitive)) {
        finalPath += U8(".src");
    }

    QString error;
    if (!writeAsciiFile(finalPath, m_lastOutput->srcCode, error)) {
        showError(U8("写入 SRC 失败：%1").arg(error));
        return;
    }

    QMessageBox::information(
        this,
        U8("导出完成"),
        U8("已生成唯一的 KUKA 程序文件：\n%1")
            .arg(QDir::toNativeSeparators(finalPath)));
}

