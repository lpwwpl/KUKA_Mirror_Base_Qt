QString U8(const char* text) { return QString::fromUtf8(text); }

QString f(double value, int precision = 6) {
    if (std::abs(value) < 0.5 * std::pow(10.0, -precision)) value = 0.0;
    return QString::number(value, 'f', precision);
}

QString vec(const mirror::Vec3& value) {
    return U8("[%1, %2, %3]")
        .arg(f(value.x), f(value.y), f(value.z));
}

QString fromUtf8String(const std::string& value) {
    return QString::fromUtf8(value.data(), static_cast<int>(value.size()));
}

std::string toUtf8String(const QString& value) {
    const QByteArray bytes = value.toUtf8();
    return std::string(bytes.constData(), static_cast<std::size_t>(bytes.size()));
}

QString frameText(const mirror::Frame& frame) {
    return fromUtf8String(mirror::formatFrame(frame));
}

bool writeUtf8File(const QString& path, const QString& text, QString& error) {
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) {
        error = file.errorString();
        return false;
    }
    QTextStream stream(&file);
    stream.setCodec("UTF-8");
    stream << text;
    return true;
}

// KUKA SRC generated by this application contains ASCII-only identifiers,
// numbers and comments. Writing raw ASCII avoids controller-side mojibake.
bool writeAsciiFile(const QString& path, const std::string& text, QString& error) {
    QFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Truncate)) {
        error = file.errorString();
        return false;
    }
    const QByteArray bytes(text.data(), static_cast<int>(text.size()));
    if (file.write(bytes) != bytes.size()) {
        error = file.errorString();
        return false;
    }
    return true;
}

